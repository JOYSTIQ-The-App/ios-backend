CREATE TYPE "social_type" AS ENUM (
  'discord',
  'kick',
  'twitch',
  'youtube',
  'xbox',
  'playstation'
);

CREATE TYPE "account_type" AS ENUM (
  'public',
  'private',
  'hidden'
);

CREATE TYPE "role_type" AS ENUM (
  'admin',
  'org',
  'gamer'
);

CREATE TYPE "status_type" AS ENUM (
  'live',
  'draft',
  'archived',
  'reported'
);

CREATE TYPE "media_type" AS ENUM (
  'none',
  'photo',
  'video'
);

CREATE TYPE "environment_type" AS ENUM (
  'classic',
  'gameroom'
);

CREATE TABLE "follows" (
  "following_user_id" integer,
  "followed_user_id" integer,
  "created_at" timestamp DEFAULT (now()),
  PRIMARY KEY ("following_user_id", "followed_user_id")
);

CREATE TABLE "users" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "email" varchar(100) UNIQUE NOT NULL,
  "username" varchar(100) UNIQUE NOT NULL,
  "role" role_type DEFAULT 'gamer',
  "account" account_type DEFAULT 'public',
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "posts" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" integer,
  "s3_key" varchar(255) DEFAULT null,
  "thumbnail_s3_key" varchar(255) DEFAULT null,
  "media" media_type NOT NULL,
  "game" varchar(100),
  "body" text,
  "status" status_type DEFAULT 'live',
  "likes" integer DEFAULT 0,
  "comments" integer DEFAULT 0,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "liked_posts" (
  "user_id" integer,
  "post_id" integer,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now()),
  PRIMARY KEY ("user_id", "post_id")
);

CREATE TABLE "comments" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" integer,
  "post_id" integer,
  "text" text,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "profiles" (
  "user_id" integer PRIMARY KEY,
  "bio" text DEFAULT '',
  "resume" text DEFAULT '',
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "socials" (
  "user_id" integer,
  "social" social_type,
  "social_username" varchar(100),
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now()),
  PRIMARY KEY ("user_id", "social")
);

CREATE TABLE "avatars" (
  "user_id" integer PRIMARY KEY,
  "avatar_s3_key" varchar(255) UNIQUE NOT NULL,
  "environment" environment_type DEFAULT 'gameroom',
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

COMMENT ON COLUMN "posts"."s3_key" IS 's3 id for content';

COMMENT ON COLUMN "posts"."body" IS 'Content of the post';

COMMENT ON COLUMN "comments"."text" IS 'Content of comment';

COMMENT ON COLUMN "profiles"."bio" IS 'Content of bio';

COMMENT ON COLUMN "profiles"."resume" IS 'Content of resume';

COMMENT ON COLUMN "avatars"."avatar_s3_key" IS 's3 id for avatar';

